# Comparison/Relational operators : They are used in comparing of values and they usually return a Boolen answer. They include a Boolen answer. They include <,>,<=,>=,==,!=

print(3 > 2)
print(3 < 2)
print(3 >= 2)
print(3 <= 2)
print(3 == 2)
print(3 != 2)

# Logical operators
# Logical AND : evaluate to true if both of the statements are true
print(3 > 2) and (2 < 3)

# Logical or : Evaluate to true if one of the statemets is true 
print(3 > 2) or (3 < 2)

# Logical not : It negates a statement
print(not(3 > 2))