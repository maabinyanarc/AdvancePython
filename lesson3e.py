# while loop.
# It is used when the looping number is known before hand.
"""
The structure of the while loop is given below:
initiate a variable,
while keybord,
condition to be checked,
increment/decrement.
"""
number = 0

while number <= 10:
    print(number)
    number = number + 1

print("======================================")    

